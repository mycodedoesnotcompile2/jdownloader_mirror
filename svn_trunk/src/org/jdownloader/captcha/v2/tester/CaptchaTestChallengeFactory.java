    /* ALTCHA: Generated by prepareTestChallenge if there is no challenge URL. */
    public static final String                                  KEY_CHALLENGE_JSON  = "challengeJson";
    /* Proxy (e.g. "socks5://user:password@host:port") for the challenge, optional. Only for interactive captchas (no image captchas). */
    public static final String                                  KEY_PROXY           = "proxy";
